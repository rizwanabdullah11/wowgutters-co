function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[,.'"]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

const lines = rawText.split('\n').map(l => l.trim()).filter(Boolean);
const cleaned = [];
const seenSlugs = new Set();

for (const line of lines) {
  if (line.includes('instagram.com') || line.includes('vercel.app')) continue;
  let cleanLine = line
    .replace(/<br>/gi, ' ')
    .replace(/,.*$/, '') // remove trailing csv metadata
    .replace(/["']/g, '')
    .trim();
  if (!cleanLine || cleanLine.length < 2) continue;
  const slug = slugify(cleanLine);
  if (!seenSlugs.has(slug)) {
    seenSlugs.add(slug);
    cleaned.push(cleanLine);
  }
}

console.log('Total unique keywords:', cleaned.length);
fs.writeFileSync('scratch/cleanedKeywords.json', JSON.stringify(cleaned, null, 2));
