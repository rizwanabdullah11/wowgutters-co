import fs from 'node:fs';
import path from 'node:path';

const projectRoot = process.cwd();

/** @returns {string[]} */
function loadAreaSlugsFromLib() {
  const p = path.join(projectRoot, 'lib', 'areaSlugs.ts');
  const t = fs.readFileSync(p, 'utf8');
  const slugs = [];
  for (const line of t.split('\n')) {
    const m = line.match(/^\s*'([^']+)',?\s*$/);
    if (m) slugs.push(m[1]);
  }
  return slugs;
}

const slugs = loadAreaSlugsFromLib();
const outPath = path.join(projectRoot, 'public', 'wow-area-search.js');

const source = `/**
 * Area search for static export (Hostinger). Works without React hydration.
 * Generated by scripts/generate-area-search.mjs — do not edit by hand.
 */
(function () {
  var AREA_SLUGS = ${JSON.stringify(slugs)};
  var NAME_ALIASES = {
    'west midlands': 'westmidlands',
    'west-midlands': 'westmidlands',
    droitwich: 'droitwich-spa',
    hollywood: 'hollywood-birmingham',
    california: 'california-birmingham',
  };

  function normalizeToSlug(query) {
    return query.toLowerCase().trim().replace(/\\s+/g, '-');
  }

  function slugToWords(slug) {
    return slug.replace(/-/g, ' ');
  }

  function resolveAreaSlug(query) {
    var trimmed = (query || '').trim();
    if (!trimmed) return null;

    var asSlug = normalizeToSlug(trimmed);
    for (var i = 0; i < AREA_SLUGS.length; i++) {
      if (AREA_SLUGS[i] === asSlug) return asSlug;
    }

    var lower = trimmed.toLowerCase().trim();
    var alias = NAME_ALIASES[lower] || NAME_ALIASES[asSlug];
    if (alias) return alias;

    for (var j = 0; j < AREA_SLUGS.length; j++) {
      if (slugToWords(AREA_SLUGS[j]) === lower) return AREA_SLUGS[j];
    }

    for (var k = 0; k < AREA_SLUGS.length; k++) {
      var slug = AREA_SLUGS[k];
      if (slug.indexOf(asSlug) !== -1 || asSlug.indexOf(slug) !== -1) return slug;
    }

    return null;
  }

  function areaSegment(slug) {
    return 'gutter-cleaning-' + slug + '/';
  }

  function siteRootRelativePrefix() {
    var protocol = window.location.protocol;
    var pathname = window.location.pathname;
    var href = window.location.href;

    try {
      pathname = decodeURIComponent(pathname);
    } catch (_) {}

    if (/\\/index\\.html?$/i.test(pathname)) {
      pathname = pathname.replace(/index\\.html?$/i, '');
    } else if (/\\.html?$/i.test(pathname)) {
      pathname = pathname.slice(0, pathname.lastIndexOf('/') + 1);
    }

    if (pathname.charAt(pathname.length - 1) !== '/') {
      pathname += '/';
    }

    if (protocol === 'file:') {
      var outMatch = pathname.match(/\\/out\\/(.*)$/i);
      if (outMatch) {
        var depth = outMatch[1].split('/').filter(Boolean).length;
        return depth === 0 ? './' : new Array(depth + 1).join('../');
      }

      var baseHref = href.split(/[?#]/)[0];
      var dir = baseHref.slice(0, baseHref.lastIndexOf('/') + 1);
      var outIdx = dir.toLowerCase().lastIndexOf('/out/');
      if (outIdx !== -1) {
        var afterOut = dir.slice(outIdx + 5);
        var depthFromHref = afterOut.split('/').filter(Boolean).length;
        return depthFromHref === 0 ? './' : new Array(depthFromHref + 1).join('../');
      }

      return './';
    }

    var httpDepth = pathname.split('/').filter(Boolean).length;
    return httpDepth === 0 ? '/' : new Array(httpDepth + 1).join('../');
  }

  function areaNavigationUrl(slug) {
    return siteRootRelativePrefix() + areaSegment(slug);
  }

  function searchWrapFor(node) {
    return node.closest('.search-input-wrap') || node.closest('.search-field') || node;
  }

  function showError(wrap, message) {
    var host = searchWrapFor(wrap);
    var err = host.querySelector('.search-error-static');
    if (!err) {
      err = document.createElement('p');
      err.className = 'search-error search-error-static';
      err.setAttribute('role', 'alert');
      host.appendChild(err);
    }
    err.textContent = message;
  }

  function clearError(wrap) {
    var host = searchWrapFor(wrap);
    var err = host.querySelector('.search-error-static');
    if (err) err.remove();
  }

  function handleSearch(field) {
    var input = field.querySelector('.search-input');
    if (!input) return;

    var slug = resolveAreaSlug(input.value);
    if (slug) {
      window.location.assign(areaNavigationUrl(slug));
      return;
    }

    var q = input.value.trim();
    showError(
      field,
      q
        ? 'No coverage page found for "' + q + '". Try Birmingham, Coventry, or Wolverhampton.'
        : 'Please enter a town or city name.',
    );
  }

  function bind(field) {
    if (field.getAttribute('data-wow-area-search-bound') === '1') return;
    field.setAttribute('data-wow-area-search-bound', '1');

    var input = field.querySelector('.search-input');
    var button = field.querySelector('.search-submit');
    if (!input) return;

    if (button) {
      button.addEventListener('click', function (event) {
        event.preventDefault();
        handleSearch(field);
      });
    }

    input.addEventListener('keydown', function (event) {
      if (event.key === 'Enter') {
        event.preventDefault();
        handleSearch(field);
      }
    });

    input.addEventListener('input', function () {
      clearError(field);
    });
  }

  function init() {
    document.querySelectorAll('.search-field').forEach(bind);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
`;

fs.writeFileSync(outPath, source, 'utf8');
console.log(`generate-area-search: wrote ${outPath} (${slugs.length} slugs)`);
